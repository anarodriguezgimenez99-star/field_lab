    static func activityAction(_ rawValue: String) -> String {
        switch rawValue {
        case "read_resource": return text("Read resource")
        case "searched_knowledge": return text("Searched knowledge")
        case "searched_references": return text("Searched references")
        case "read_reference": return text("Read reference")
        case "read_project_context": return text("Read project context")
        case "read_project_constraints": return text("Read project constraints")
        case "read_tool_knowledge": return text("Read tool knowledge")
        case "read_project_decisions": return text("Read project decisions")
        case "read_experiment": return text("Read experiment")
        case "list_experiment_runs": return text("Listed experiment runs")
        case "compare_runs_metadata": return text("Compared run metadata")
        case "search_experiments": return text("Searched experiments")
        case "read_best_run": return text("Read best run")
        case "read_recipe": return text("Read recipe")
        case "read_workflow": return text("Read workflow")
        case "proposed_reference_tags": return text("Proposed reference tags")
        case "approved_reference_tags": return text("Approved reference tags")
        case "rejected_proposal": return text("Rejected proposal")
        case "added_working_note": return text("Added working note")
        case "saved_session_summary": return text("Saved session summary")
        default:
            if rawValue.hasPrefix("proposed_") || rawValue.hasPrefix("approved_") {
                let prefix = rawValue.hasPrefix("proposed_") ? "proposed_" : "approved_"
                let kind = String(rawValue.dropFirst(prefix.count))
                let kindName = switch kind {
                case "promptBlock": "Prompt Block"
                case "learning": "Learning"
                case "recipe": "Recipe"
                case "decision": "Decision"
                case "reference": "Reference"
                case "style": "Style"
                case "experiment": "Experiment"
                case "note": "Note"
                case "resource": "Resource"
                case "idea": "Idea"
                case "workingMemory": "Working memory"
                case "canonicalMemory": "Canonical memory"
                case "sessionSummary": "Session summary"
                case "flow": "Flow"
                default: kind.capitalized
                }
                return "\(text(prefix == "proposed_" ? "Proposed" : "Approved")) \(text(kindName))"
            }
            return rawValue.replacingOccurrences(of: "_", with: " ").capitalized
        }
    }

