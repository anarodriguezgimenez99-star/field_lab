    static var currentLanguage: FieldLanguage {
        let groupID = Bundle.main.object(forInfoDictionaryKey: "FIELD_APP_GROUP_ID") as? String
        let sharedLanguage = groupID.flatMap { UserDefaults(suiteName: $0) }?.string(forKey: FieldLanguage.preferenceKey)
        let standardLanguage = UserDefaults.standard.string(forKey: FieldLanguage.preferenceKey)
        let storedLanguage = Bundle.main.object(forInfoDictionaryKey: "NSExtension") == nil
            ? standardLanguage ?? sharedLanguage
            : sharedLanguage ?? standardLanguage
        return FieldLanguage(
            rawValue: storedLanguage ?? FieldLanguage.spanish.rawValue
        ) ?? .spanish
    }

    static func text(_ source: String, language: FieldLanguage? = nil) -> String {
        let selectedLanguage = language ?? currentLanguage

        return switch selectedLanguage {
        case .spanish: spanish[source] ?? source
        case .english: english[source] ?? source
        }
    }

    static func format(_ source: String, _ arguments: CVarArg...) -> String {
        String(format: text(source), locale: currentLanguage.locale, arguments: arguments)
    }

    static func pluralized(_ count: Int, singular: String, plural: String) -> String {
        "\(count) \(text(count == 1 ? singular : plural))"
    }

